const tables: Record<LocaleId, Record<MessageKey, string>> = {
  "en-US": en,
  "vi-VN": vi,
  "de-DE": de,
  "fr-FR": fr,
};

export function localeMeta(id: LocaleId) {
  return LOCALES.find((l) => l.id === id) ?? LOCALES[0];
}

export function guessLocale(language: string | undefined): LocaleId {
  const lang = (language ?? "").toLowerCase();
  if (lang.startsWith("vi")) return "vi-VN";
  if (lang.startsWith("de")) return "de-DE";
  if (lang.startsWith("fr")) return "fr-FR";
  return "en-US";
}

export function translate(locale: LocaleId, key: MessageKey, vars?: Record<string, string | number>) {
  const raw = tables[locale][key] ?? tables["en-US"][key];
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
}

export function pluralCategory(locale: LocaleId, n: number): "one" | "other" {
  if (locale === "fr-FR") return n === 0 || n === 1 ? "one" : "other";
  if (locale === "vi-VN") return "other";
  return n === 1 ? "one" : "other";
}
